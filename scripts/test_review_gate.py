"""Tests for review_gate.py. Run: python3 -m unittest discover -s scripts"""

import unittest

from review_gate import evaluate


def comment(body, at, assoc="OWNER"):
    return {"body": body, "created_at": at, "author_association": assoc}


FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def pr(ref="feat/x", author="jkorinth", head_repo="jkorinth/rusthour"):
    return {
        "user": {"login": author},
        "head": {"ref": ref, "repo": {"full_name": head_repo}},
        "base": {"repo": {"full_name": "jkorinth/rusthour"}},
    }


RELEASE = pr("release-please--branches--main", "github-actions[bot]")


class EvaluateTest(unittest.TestCase):
    def test_regular_pr_needs_no_review(self):
        self.assertEqual(evaluate(pr(), []), ("success", "no reviews required"))

    def test_regular_pr_latest_request_blocks(self):
        comments = [
            comment("**Architect review**\nVERDICT: APPROVE", "2026-01-01T00:00:00Z"),
            comment("**UX review**\nVERDICT: REQUEST CHANGES. Fix item 1.", "2026-01-02T00:00:00Z"),
            # Not a review: no bold role heading, or an outsider, or no verdict line.
            comment("Rebased.\nVERDICT: APPROVE", "2026-01-03T00:00:00Z"),
            comment("**UX review**\nVERDICT: APPROVE", "2026-01-03T00:00:00Z", assoc="NONE"),
            comment("**UX review**\nI'd say VERDICT: APPROVE soon", "2026-01-03T00:00:00Z"),
        ]
        self.assertEqual(evaluate(pr(), comments), ("failure", "UX requested changes"))
        recheck = comment("**UX re-check**\nVERDICT: APPROVE" + FOOTER, "2026-01-04T00:00:00Z")
        self.assertEqual(evaluate(pr(), comments + [recheck])[0], "success")

    def test_release_pr_needs_the_milestone_review(self):
        self.assertEqual(evaluate(RELEASE, []),
                         ("failure", "waiting for: architect review, UX review"))
        comments = [
            comment("**Architect milestone review**\nVERDICT: REQUEST CHANGES", "2026-01-01T00:00:00Z"),
            comment("**Architect re-check**\nVERDICT: APPROVE" + FOOTER, "2026-01-02T00:00:00Z"),
            comment("**UX milestone review**\nVERDICT: APPROVE", "2026-01-02T00:00:00Z"),
        ]
        self.assertEqual(evaluate(RELEASE, comments), ("success", "architect ✓, UX ✓"))

    def test_fork_with_release_please_branch_is_a_regular_pr(self):
        fork = pr("release-please--branches--main", "github-actions[bot]", "mallory/rusthour")
        self.assertEqual(evaluate(fork, []), ("success", "no reviews required"))


if __name__ == "__main__":
    unittest.main()
