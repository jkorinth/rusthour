"""Tests for review_gate.py. Run: python3 -m unittest discover -s scripts"""

import unittest

from review_gate import evaluate


def comment(body, at, assoc="OWNER"):
    return {"body": body, "created_at": at, "author_association": assoc}


FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
CORE = ["crates/rusthour-core/src/lib.rs"]
VIZ = ["crates/rusthour-viz/src/main.rs"]


def pr(ref="feat/x", author="jkorinth", head_repo="jkorinth/rusthour"):
    return {
        "user": {"login": author},
        "head": {"ref": ref, "repo": {"full_name": head_repo}},
        "base": {"repo": {"full_name": "jkorinth/rusthour"}},
    }


class EvaluateTest(unittest.TestCase):
    def test_latest_verdict_per_role_wins(self):
        comments = [
            comment("**Architect review**\n\nVERDICT: REQUEST CHANGES", "2026-01-01T00:00:00Z"),
            comment("**Architect re-check** (head `abc`)\n\nVERDICT: APPROVE" + FOOTER, "2026-01-02T00:00:00Z"),
        ]
        self.assertEqual(evaluate(pr(), CORE, comments), ("success", "architect ✓"))

    def test_ux_required_for_frontend_crates(self):
        arch = comment("**Architect review**\nVERDICT: APPROVE", "2026-01-01T00:00:00Z")
        self.assertEqual(evaluate(pr(), VIZ, [arch]), ("failure", "waiting for: UX review"))
        ux = comment("**UX final check**\nVERDICT: APPROVE" + FOOTER, "2026-01-02T00:00:00Z")
        self.assertEqual(evaluate(pr(), VIZ, [arch, ux]), ("success", "architect ✓, UX ✓"))

    def test_request_changes_blocks_and_noise_is_ignored(self):
        comments = [
            comment("**Architect review**\nVERDICT: APPROVE", "2026-01-01T00:00:00Z"),
            comment("**UX review**\nVERDICT: REQUEST CHANGES. Fix item 1.", "2026-01-02T00:00:00Z"),
            # Not a review: no bold role heading, or an outsider, or no verdict line.
            comment("Rebased.\nVERDICT: APPROVE", "2026-01-03T00:00:00Z"),
            comment("**UX review**\nVERDICT: APPROVE", "2026-01-03T00:00:00Z", assoc="NONE"),
            comment("**UX review**\nI'd say VERDICT: APPROVE soon", "2026-01-03T00:00:00Z"),
        ]
        self.assertEqual(evaluate(pr(), ["crates/rusthour-api/src/lib.rs"], comments),
                         ("failure", "UX requested changes"))

    def test_release_please_pr_is_exempt(self):
        state, desc = evaluate(pr("release-please--branches--main", "github-actions[bot]"), VIZ, [])
        self.assertEqual(state, "success")
        self.assertIn("release PR", desc)

    def test_fork_with_release_please_branch_is_not_exempt(self):
        fork = pr("release-please--branches--main", "github-actions[bot]", "mallory/rusthour")
        self.assertEqual(evaluate(fork, VIZ, []),
                         ("failure", "waiting for: architect review, UX review"))


if __name__ == "__main__":
    unittest.main()
